// 이 파일은 "가챠 등급"이 어떤 종류가 있는지 정의합니다.
// enum(열거형)은 정해진 몇 가지 값 중 하나만 가질 수 있는 타입입니다.
// 예: 등급은 R, SR, SSR, LR 이 네 가지 중 하나만 될 수 있습니다.
namespace Gacha
{
    // = 0, 1, 2, 3 처럼 숫자를 붙여두면, "숫자가 클수록 희귀한 등급"이라는 규칙을
    // 코드 여러 곳(천장 로직, 정렬 등)에서 그대로 활용할 수 있습니다.
    public enum GachaTier
    {
        R = 0,   // 가장 흔한 등급 (60% 확률)
        SR = 1,  // 중간 등급 (25% 확률)
        SSR = 2, // 고급 등급 (12% 확률)
        LR = 3,  // 최상위 등급, 천장의 대상 (3% 확률)
    }
}
